APPLY = os.environ.get("BATCH6_APPLY") == "1"
HYPE = ["必吃","天花板","yyds","YYDS","封神","宝藏","不踩雷","闭眼冲","绝绝子","网红","打卡","出片","氛围感","环境优雅","服务周到","绝赞"]

def main():
    rests = C.fetch_all("restaurants", "id,name,semantic_description,is_curated", order_col="id")
    by_id = {r["id"]: r for r in rests}
    bad_len, bad_hype, missing = [], [], []
    for rid, txt in DESC.items():
        if rid not in by_id: missing.append(rid); continue
        if not by_id[rid].get("is_curated"): print("WARN not curated:", rid)
        if not (50 <= len(txt) <= 150): bad_len.append((rid, len(txt)))
        for w in HYPE:
            if w in txt: bad_hype.append((rid, w)); break
    print(f"待写 {len(DESC)} 家 | 库内缺失id={missing}")
    print(f"长度越界(应50-150)={bad_len}")
    print(f"命中软广词={bad_hype}")
    # 乱码复检：不应残留 [ " 等引号方括号
    junk = [(rid,txt) for rid,txt in DESC.items() if any(c in txt for c in ['[',']','"','【'])]
    print(f"残留括号引号={[r for r,_ in junk]}")
    print("\n=== 样例预览（前4 + 抽样后4）===")
    ids=list(DESC)
    for rid in ids[:4]+ids[-4:]:
        print(f"[id={rid}] {by_id[rid]['name']}  新{len(DESC[rid])}字: {DESC[rid]}")
    if not APPLY:
        print("\n[DRY-RUN] BATCH6_APPLY=1 写库"); return
    bdir = pathlib.Path("/app/data/backups"); bdir.mkdir(parents=True, exist_ok=True)
    bf = bdir / f"batch6_semdesc_batch2_backup_{C.today()}.jsonl"
    C.write_jsonl(str(bf), [{"id":rid,"old_semantic_description":by_id[rid]["semantic_description"]} for rid in DESC])
    print(f"备份: {bf}")
    ok=fail=0
    for rid,txt in DESC.items():
        r=C.req("PATCH",f"/restaurants?id=eq.{rid}",json={"semantic_description":txt})
        if r.status_code in (200,204): ok+=1
        else: fail+=1; print(f"[FAIL]{rid}:{r.status_code} {r.text[:120]}",file=sys.stderr)
        time.sleep(0.04)
    ids=",".join(str(i) for i in DESC)
    rv=C.req("GET",f"/restaurants?select=id,semantic_description&id=in.({ids})")
    chk={row["id"]:row["semantic_description"] for row in rv.json()}
    verified=sum(1 for rid,txt in DESC.items() if chk.get(rid)==txt)
    print(f"写库 ok={ok} fail={fail} | 回读一致 {verified}/{len(DESC)}")

main()
